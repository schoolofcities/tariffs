# ── Helper functions ──────────────────────────────────────────────────────────
def haversine_km(lat1, lon1, lat2, lon2):
    """Great-circle distance in km."""
    R = 6371
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlam = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlam / 2) ** 2
    return R * 2 * math.asin(math.sqrt(a))


def min_border_dist(lat, lon):
    """Minimum haversine distance (km) from a point to any border reference."""
    return min(haversine_km(lat, lon, bp[0], bp[1]) for bp in CANADIAN_BORDER_POINTS)


# ── Main ──────────────────────────────────────────────────────────────────────
def main():
    # Load inputs
    airports = pd.read_excel(ENPLANE_PATH)
    airports = airports.dropna(subset=['Locid', 'City', 'ST'])

    trips    = pd.read_csv(TRIPS_PATH)
    msa_list = sorted(trips['METRO'].unique())

    # Build airport → MSA lookup, validate against trips MSA list
    airport_rows = []
    for _, row in airports.iterrows():
        iata = str(row['Locid']).strip()
        msa  = IATA_TO_MSA.get(iata)
        if msa and msa not in msa_list:
            msa = None          # discard if not in trips MSA list
        airport_rows.append({
            'IATA':              iata,
            'MSA':               msa,
            'CY24_Enplanements': row.get('CY 24 Enplanements'),
            'CY23_Enplanements': row.get('CY 23 Enplanements'),
        })
    airport_df = pd.DataFrame(airport_rows)

    # Aggregate enplanements to MSA level
    msa_enplane = (
        airport_df[airport_df['MSA'].notna()]
        .groupby('MSA', as_index=False)
        .agg(
            CY24_Enplanements=('CY24_Enplanements', 'sum'),
            CY23_Enplanements=('CY23_Enplanements', 'sum'),
            IATA_codes=('IATA', lambda x: ', '.join(sorted(x.dropna())))
        )
    )

    # Build MSA feature table
    rows = []
    for msa in msa_list:
        coords = MSA_COORDS.get(msa)
        if coords:
            lat, lon  = coords
            dist      = min_border_dist(lat, lon)
        else:
            lat = lon = dist = None
        rows.append({'MSA': msa, 'lat': lat, 'lon': lon, 'dist_to_border_km': dist})

    msa_features = pd.DataFrame(rows)

    # Merge enplanements
    msa_features = msa_features.merge(msa_enplane, on='MSA', how='left')

    # Save
    msa_features.to_csv(OUTPUT_PATH, index=False)
    print(f"Saved {OUTPUT_PATH}")
    print(f"  MSAs: {len(msa_features)}")
    print(f"  With coords:       {msa_features['lat'].notna().sum()}")
    print(f"  With enplanements: {msa_features['CY24_Enplanements'].notna().sum()}")


if __name__ == "__main__":
    main()
